-- =====================================================================
-- ERP Albion - Modulo Inventario: Depositos, Existencias, Movimientos
--
-- Se investigo la legacy antes de disenar: existe `hist_existencia`
-- (702 filas) y `movimientos_almacen` (4 filas: catalogo de depositos).
-- hist_existencia NO se importa -- es una carga unica del 20/07/2017,
-- las 702 filas tienen motivo='INICIAL' y la misma fecha, nunca se
-- volvio a usar despues (no hay ninguna fila de compra/consumo/ajuste
-- posterior). Importarla como "stock actual" mostraria numeros falsos
-- de hace 9 anios. Se usan si los NOMBRES de movimientos_almacen como
-- semilla real del catalogo de depositos nuevo (existencias y
-- movimientos arrancan vacios, es una funcionalidad nueva de verdad).
--
-- Decisiones confirmadas con el usuario 2026-08-27:
-- - stock_minimo es GLOBAL por articulo (no por deposito+articulo),
--   se compara contra la suma en todos los depositos. Vive en
--   catalogo.articulos, no en una tabla aparte.
-- - motivo de movimiento es catalogo fijo (motivos_movimiento), no
--   texto libre -- mismo criterio que tipos_orden/sectores_produccion.
-- - Transferencias entre depositos son un tipo de movimiento propio
--   (TRANSFERENCIA) con deposito origen (deposito_id) + destino
--   (deposito_destino_id) en la misma fila, no un par entrada/salida
--   sin vinculo.
--
-- Ledger inmutable: movimientos_stock no tiene UPDATE/DELETE expuesto
-- desde la API -- para corregir un error se postea un movimiento
-- nuevo (ej. un AJUSTE), nunca se edita/borra el historico. existencias
-- es una tabla materializada (cache) que se recalcula transaccionalmente
-- cada vez que se postea un movimiento, no es la fuente de verdad.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS inventario;

DO $$ BEGIN
    CREATE TYPE inventario.tipo_movimiento_stock AS ENUM ('ENTRADA', 'SALIDA', 'TRANSFERENCIA');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
    CREATE TYPE inventario.aplica_movimiento AS ENUM ('ENTRADA', 'SALIDA', 'AMBOS');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS inventario.depositos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    direccion   VARCHAR(255),
    activo      BOOLEAN NOT NULL DEFAULT true,
    creado_por  BIGINT REFERENCES core.usuarios(id),
    creado_en   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS inventario.depositos_empresas (
    deposito_id BIGINT NOT NULL REFERENCES inventario.depositos(id) ON DELETE CASCADE,
    empresa_id  BIGINT NOT NULL REFERENCES core.empresas(id) ON DELETE CASCADE,
    PRIMARY KEY (deposito_id, empresa_id)
);

CREATE TABLE IF NOT EXISTS inventario.existencias (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deposito_id    BIGINT NOT NULL REFERENCES inventario.depositos(id) ON DELETE CASCADE,
    articulo_id    BIGINT NOT NULL REFERENCES catalogo.articulos(id),
    cantidad       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (deposito_id, articulo_id)
);
CREATE INDEX IF NOT EXISTS idx_existencias_articulo ON inventario.existencias (articulo_id);

CREATE TABLE IF NOT EXISTS inventario.motivos_movimiento (
    id       SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(60) NOT NULL UNIQUE,
    aplica_a inventario.aplica_movimiento NOT NULL
);

CREATE TABLE IF NOT EXISTS inventario.movimientos_stock (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deposito_id         BIGINT NOT NULL REFERENCES inventario.depositos(id),
    deposito_destino_id BIGINT REFERENCES inventario.depositos(id), -- solo TRANSFERENCIA
    articulo_id         BIGINT NOT NULL REFERENCES catalogo.articulos(id),
    tipo                inventario.tipo_movimiento_stock NOT NULL,
    cantidad            NUMERIC(14, 2) NOT NULL CHECK (cantidad > 0), -- siempre positiva, el signo lo da `tipo`
    motivo_id           SMALLINT REFERENCES inventario.motivos_movimiento(id),
    referencia          VARCHAR(200),
    nota                TEXT,
    usuario_id          BIGINT REFERENCES core.usuarios(id),
    fecha               TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_movimientos_stock_deposito ON inventario.movimientos_stock (deposito_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_stock_articulo ON inventario.movimientos_stock (articulo_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_stock_fecha ON inventario.movimientos_stock (fecha);

ALTER TABLE catalogo.articulos
    ADD COLUMN IF NOT EXISTS stock_minimo NUMERIC(14, 2);

