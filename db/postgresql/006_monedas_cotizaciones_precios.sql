CREATE TABLE catalogo.cotizaciones (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moneda_id    SMALLINT NOT NULL REFERENCES catalogo.monedas(id),
    tasa_cambio  NUMERIC(12,4) NOT NULL,  -- valor de 1 USD en esta moneda (USD siempre tasa=1.0000, moneda base)
    fecha        TIMESTAMPTZ NOT NULL DEFAULT now(),
    fuente       VARCHAR(20) NOT NULL DEFAULT 'MANUAL' CHECK (fuente IN ('MANUAL', 'BNA_AUTO')),
    creado_por   BIGINT REFERENCES core.usuarios(id)
);
CREATE INDEX idx_cotizaciones_moneda_fecha ON catalogo.cotizaciones(moneda_id, fecha DESC);
COMMENT ON TABLE catalogo.cotizaciones IS
    'Historial append-only de tipo de cambio por moneda (siempre respecto a USD). Nunca se actualiza una fila existente: cada cambio de cotizacion inserta una fila nueva. La cotizacion vigente de una moneda es la de fecha mas reciente. fuente=BNA_AUTO queda reservado para cuando se conecte la carga automatica desde el BNA (pendiente); por ahora toda carga es MANUAL.';

