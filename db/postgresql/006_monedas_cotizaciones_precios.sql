-- ERP Albion - Monedas, historial de cotizaciones y precios en USD (Compras)
--
-- Decision del usuario (2026-08-24): de los 3 pares de precio que tenia
-- `articulos` en el legacy (pesos/UltimoPrecio, USD/UltimoPrecio2, y un
-- tercero sin identificar/UltimoPrecio3), solo el precio en USD importa
-- de aca en adelante -- el resto no se migra. Ademas, a diferencia del
-- legacy (que solo guardaba el ULTIMO precio, sobreescrito cada vez, sin
-- historial ni motivo de cambio), esta version guarda TODO el historial:
-- cada cambio de precio es una fila nueva, nunca un UPDATE.
--
-- Mismo criterio para el tipo de cambio: el legacy tenia una tabla
-- `monedas` con una sola tasa "actual" por moneda (se pisaba en cada
-- actualizacion -- confirmado en el dump, comentario original
-- "Dolar estadounidense (Cambio BNA)"). Se reemplaza por
-- catalogo.cotizaciones, un historial append-only, preparado para que
-- una tarea futura cargue la cotizacion BNA automaticamente
-- (fuente='BNA_AUTO') ademas de la carga manual (fuente='MANUAL') --
-- esa tarea de scraping/consumo de la API del BNA queda pendiente,
-- todavia no se construyo.
--
-- catalogo.articulo_precios queda creada pero SIN poblar en este archivo:
-- catalogo.articulos sigue vacia (la migracion real de articulos todavia
-- no se hizo), asi que no hay articulo_id validos para cargar el
-- historial de precios legacy todavia. Se puebla junto con la migracion
-- de articulos.
-- =====================================================================

CREATE TABLE catalogo.monedas (
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_iso  VARCHAR(3) NOT NULL UNIQUE,
    nombre      VARCHAR(50) NOT NULL,
    simbolo     VARCHAR(5),
    activa      BOOLEAN NOT NULL DEFAULT TRUE
);
