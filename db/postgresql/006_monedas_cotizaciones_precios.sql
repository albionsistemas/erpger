-- legacy: el campo "Razon" de articulos codificaba esto como un factor
-- numerico (1 / 0.001 / 0.000001) en vez de una categoria explicita.
-- Confirmado contra el dump: Razon=1 en piezas/rodamientos/motores
-- (se cuentan por unidad), Razon=0.001 en perfileria SAE/AISI (se
-- vende por metro, se corta y cobra por mm), Razon=0.000001 en chapas/
-- bandas (se vende por m2, se corta y cobra por mm2). Sirve para saber
-- como interpretar catalogo.articulo_precios.precio_usd al calcular el
-- costo de un recorte especifico (contra ANCHO/LARGO de despiece_ot).

ALTER TABLE catalogo.articulos
    ADD COLUMN modo_venta catalogo.modo_venta;

CREATE TABLE catalogo.articulo_precios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id BIGINT NOT NULL REFERENCES catalogo.articulos(id),
    precio_usd  NUMERIC(14,4) NOT NULL,
    fecha       TIMESTAMPTZ NOT NULL DEFAULT now(),
    motivo      VARCHAR(255),
    creado_por  BIGINT REFERENCES core.usuarios(id),
    creado_en   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_articulo_precios_articulo_fecha ON catalogo.articulo_precios(articulo_id, fecha DESC);
COMMENT ON TABLE catalogo.articulo_precios IS
    'Historial append-only de precio en USD por articulo (legacy: UltimoPrecio2/precioRazon2 -- las columnas en pesos y la tercera sin identificar no se migran, decision del usuario). Nunca se actualiza una fila existente: cada cambio de precio inserta una fila nueva con motivo y quien lo cargo. El precio vigente de un articulo es el de fecha mas reciente. precio_usd es el precio comercial (por unidad, por metro o por m2 segun articulos.modo_venta) -- el precio de un corte puntual se calcula on-the-fly contra ANCHO/LARGO de despiece_ot, no se guarda pre-calculado (en el legacy ese precalculo -precioRazon- se desincronizaba del precio base en ~5% de los casos).';
