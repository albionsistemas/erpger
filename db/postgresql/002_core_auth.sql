-- para "este usuario edita su sector y solo ve los demas" y no requiere
-- inventar un catalogo de roles que despues hay que mantener sincronizado
-- con los permisos reales. Un usuario "superadmin" (flag booleano)
-- bypassea todo chequeo de permisos.
