-- ---------------------------------------------------------------------
-- Completar core.usuarios (creada como stub en 001_ingenieria_schema.sql)
-- ---------------------------------------------------------------------

ALTER TABLE core.usuarios
    ADD COLUMN IF NOT EXISTS password_hash  VARCHAR(255),
    ADD COLUMN IF NOT EXISTS email          VARCHAR(255) UNIQUE,
    ADD COLUMN IF NOT EXISTS imagen_url     VARCHAR(255),
    ADD COLUMN IF NOT EXISTS activo         BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS es_superadmin  BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS creado_en      TIMESTAMPTZ NOT NULL DEFAULT now();

COMMENT ON TABLE core.usuarios IS
    'Usuarios del sistema (login). Distinto de ingenieria.operarios, que son personas de planta que pueden o no tener una cuenta aca. password_hash queda NULL para los usuarios creados solo por el ETL (logins legacy sin password real todavia); no pueden loguearse hasta que un superadmin les asigne una contrasena.';

-- ---------------------------------------------------------------------
-- MODULOS (Ingenieria, Planificacion, Ventas, Compras, RRHH, Almacen...)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS core.modulos (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave   VARCHAR(30) NOT NULL UNIQUE,   -- usada en el codigo (guards, frontend), no traducible
    nombre  VARCHAR(60) NOT NULL           -- nombre visible en la UI
);

INSERT INTO core.modulos (clave, nombre) VALUES
    ('ingenieria', 'Ingenieria'),
    ('planificacion', 'Planificacion'),
    ('ventas', 'Ventas'),
    ('compras', 'Compras'),
    ('rrhh', 'Recursos Humanos'),
    ('almacen', 'Almacen')
ON CONFLICT (clave) DO NOTHING;
-- Lista extensible: un superadmin puede dar de alta nuevos modulos desde
-- la UI a medida que se sumen (CRUD simple sobre esta tabla).

-- ---------------------------------------------------------------------
-- PERMISOS: nivel de acceso de cada usuario a cada modulo
-- ---------------------------------------------------------------------

DO $$ BEGIN
    CREATE TYPE core.nivel_permiso AS ENUM ('SIN_ACCESO', 'VER', 'EDITAR');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;
-- ENUM nativo (a diferencia de los catalogos de ingenieria.*) porque es
-- un dominio realmente cerrado: estos 3 valores estan hardcodeados en la
-- logica de los guards del backend, no son datos que un admin vaya a
-- ampliar desde la UI.

CREATE TABLE IF NOT EXISTS core.usuario_modulo_permisos (
    usuario_id  BIGINT NOT NULL REFERENCES core.usuarios(id) ON DELETE CASCADE,
    modulo_id   SMALLINT NOT NULL REFERENCES core.modulos(id) ON DELETE CASCADE,
    nivel       core.nivel_permiso NOT NULL DEFAULT 'SIN_ACCESO',
    PRIMARY KEY (usuario_id, modulo_id)
);

CREATE INDEX IF NOT EXISTS idx_usuario_modulo_permisos_usuario ON core.usuario_modulo_permisos(usuario_id);

