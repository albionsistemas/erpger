-- =====================================================================
-- ERP Albion - Marcas + ajustes a catalogo.articulos (Compras)
--
-- Decisiones confirmadas con el usuario sobre los campos de la tabla
-- legacy `articulos` que todavia no estaban modelados:
--
-- - `marca` (int) SI es una relacion real -> tabla legacy `marcas` (14
--   filas: ALBION, AGRICOLA ITALIANA, SIMON, etc). No es solo un tag de
--   fabricante: cada marca trae moneda/coeficiente/forma de pago, o sea
--   condiciones de compra -- pertenece a Compras. Se crea catalogo.marcas
--   preservando el id legacy (0 uso hoy en catalogo.articulos, que sigue
--   vacia, pero evita un remapeo cuando se migren los articulos reales).
-- - `rubro` (varchar) SI es una relacion real -> catalogo.rubros, que ya
--   existe (poblada por el ETL desde rubros_albion). Solo faltaba la FK
--   en catalogo.articulos.
-- - `UltimoProveedor`: NO se migra. Esta vacio en el 100% de las 10665
--   filas del dump (6029 NULL + 4636 ''), es un campo muerto del legacy.
-- - `estado_art`: NO se migra. Ademas de los valores esperados
--   (Nuevo/Verificado/blank), ~107 filas tienen numeros sueltos cargados
--   por error (probablemente precios que se filtraron a la columna
--   equivocada). Se descarta la columna `estado` que ya existia en el
--   DDL original (tabla catalogo.articulos sigue vacia, sin perdida de
--   datos).
-- - `tipo_equipo`: NO se migra. 96% de las filas tiene 0 (sin uso) y no
--   se identifico a que tabla/concepto legacy referencia; se omite hasta
--   que el usuario aclare su significado.
-- - `NC` (Nomenclatura Comun / codigo aduanero) SI se guarda, pero como
--   atributo de texto plano -- no referencia ninguna otra tabla.
--
-- Tambien corrige el ownership: el CRUD de catalogo.articulos (y de este
-- catalogo compartido en general) lo administra Compras, no Almacen
-- (ver backend/src/articulos/articulos.controller.ts y
-- frontend/src/providers/accessControlProvider.ts, actualizados en el
-- mismo cambio que este archivo).
-- =====================================================================

CREATE TABLE IF NOT EXISTS catalogo.marcas (
    id           SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30) NOT NULL UNIQUE,
    moneda       VARCHAR(4),
    coeficiente  SMALLINT,       -- legacy: coef (recargo/markup de la marca)
    forma_pago   VARCHAR(100)
);
-- legacy: marcas. Se puebla mas abajo preservando el id original (por
-- si en el futuro catalogo.articulos.marca_id necesita resolverse 1:1
-- contra el legacy sin crosswalk adicional).

ALTER TABLE catalogo.articulos
    DROP COLUMN IF EXISTS estado,
    ADD COLUMN IF NOT EXISTS nc        VARCHAR(30),                                -- legacy: NC. Atributo plano, sin relacion.
    ADD COLUMN IF NOT EXISTS marca_id  SMALLINT REFERENCES catalogo.marcas(id),    -- legacy: marca
    ADD COLUMN IF NOT EXISTS rubro_id  SMALLINT REFERENCES catalogo.rubros(id);    -- legacy: rubro

