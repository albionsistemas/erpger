CREATE TABLE catalogo.categorias (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(100) NOT NULL UNIQUE
);
-- legacy: tiposdearticulos (unifica select_1/select_2/select_3, redundantes).
