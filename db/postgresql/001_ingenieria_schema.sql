CREATE TABLE ingenieria.ordenes_fabricacion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_of           INTEGER NOT NULL UNIQUE,   -- numero visible de negocio
    tipo_orden_id       SMALLINT NOT NULL REFERENCES ingenieria.tipos_orden(id),
    cliente_id          BIGINT REFERENCES catalogo.clientes(id),
    fecha               DATE NOT NULL,
    fecha_entrega       DATE,
    rubro_id            SMALLINT REFERENCES catalogo.rubros(id),
    referencia          VARCHAR(50),
    nota                TEXT,
    layout_url          VARCHAR(255),
    pautas_url          VARCHAR(255),
    vendedor_id         BIGINT REFERENCES core.usuarios(id),
    estado_id           SMALLINT NOT NULL REFERENCES ingenieria.estados_of(id),
    creado_por          BIGINT REFERENCES core.usuarios(id),
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON COLUMN ingenieria.ordenes_fabricacion.numero_of IS
    'Legacy: la columna "of" original guardaba el TIPO (redundante con ordenes_tipo), no un numero. El numero visible = id_of + 3000, CONFIRMADO en el codigo fuente PHP legacy (of_listar.php linea 264: $numero_of = $fila["id_of"] + 3000).';
COMMENT ON TABLE ingenieria.ordenes_fabricacion IS
    'legacy: of. Columnas descartadas por falta de uso real en los datos de muestra: t_clientefacturar, t_clientecuit, usuariocontable, datecontable, t_optionsRadios (confirmar con negocio antes de migrar historico, probablemente pertenecen a Facturacion).';

CREATE TABLE ingenieria.ordenes_trabajo (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    of_id                   BIGINT NOT NULL REFERENCES ingenieria.ordenes_fabricacion(id) ON DELETE CASCADE,
    numero_ot                INTEGER NOT NULL UNIQUE, -- = id_ot + 5000, CONFIRMADO en el legacy (ej. maquina_convertir_clon.php: $id_ot_real = $_REQUEST["idPlano"] - 5000)
    maquina_id              BIGINT REFERENCES ingenieria.maquinas(id),
    maquina_nombre          VARCHAR(150) NOT NULL, -- texto libre historico cuando no matchea catalogo
    cantidad                SMALLINT NOT NULL DEFAULT 1,
    plano                   VARCHAR(20),
    fecha                   DATE NOT NULL,
    fecha_ejecucion         DATE,
    nota                    TEXT,
    referencia               VARCHAR(200),
    observaciones            VARCHAR(200),
    estado_id               SMALLINT REFERENCES ingenieria.estados_ot(id),
    revisado_por             BIGINT REFERENCES core.usuarios(id), -- legacy: usuario_rev
    placa                   VARCHAR(20),
    serie                   VARCHAR(10),
    motor                   VARCHAR(80),
    ficha_tecnica_id        BIGINT,     -- legacy: id_ficha, sin tabla de fichas migrada aun (fuera de alcance)
    ficha_documento         VARCHAR(200), -- legacy: ficha (ruta/nombre de archivo, distinto de id_ficha)
    version                 VARCHAR(8),
    ftd                     SMALLINT,   -- legacy: ftd, significado no confirmado con negocio, se preserva sin transformar
    creado_por              BIGINT REFERENCES core.usuarios(id),
    creado_en                TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE ingenieria.ordenes_trabajo IS 'legacy: o_trabajo. Etapas ING/CORTE/PLEG/FABRIC/MECA/PINT/ARMA/ESP -> ver ot_etapas (las 7 son flags de avance por sector, no responsables). Terceros 1..5 -> ver ot_terceros. imagen1..6 -> ver ot_imagenes.';

-- Reemplaza las 6 etapas fijas (con su propio par fecha/usuario) por filas.
CREATE TABLE ingenieria.ot_etapas (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ot_id           BIGINT NOT NULL REFERENCES ingenieria.ordenes_trabajo(id) ON DELETE CASCADE,
    sector_id       SMALLINT NOT NULL REFERENCES ingenieria.sectores_produccion(id),
    completada      BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_completada DATE,
    usuario_id      BIGINT REFERENCES core.usuarios(id),
    UNIQUE (ot_id, sector_id)
);

-- Reemplaza TERCERO1..5 / F_INICIO_1..5 / F_ENTREGA_1..5
CREATE TABLE ingenieria.ot_terceros (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ot_id           BIGINT NOT NULL REFERENCES ingenieria.ordenes_trabajo(id) ON DELETE CASCADE,
    tercero         VARCHAR(60) NOT NULL,
    fecha_inicio    DATE,
    fecha_entrega   DATE
);

-- Reemplaza imagen1..imagen6
CREATE TABLE ingenieria.ot_imagenes (
    id      BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ot_id   BIGINT NOT NULL REFERENCES ingenieria.ordenes_trabajo(id) ON DELETE CASCADE,
    url     VARCHAR(255) NOT NULL,
    orden   SMALLINT NOT NULL DEFAULT 0
);

-- =====================================================================
