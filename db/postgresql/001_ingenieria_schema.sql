-- =====================================================================
-- ERP Albion - Modulo Ingenieria / Ordenes de Fabricacion (OF)
-- Esquema PostgreSQL de destino (migracion desde MySQL 5.x legacy)
--
-- Fuente de analisis: backup_desarrollo2013.sql (dump local, solo lectura)
-- Convenciones:
--   - snake_case, en minusculas
--   - PK: id BIGINT GENERATED ALWAYS AS IDENTITY
--   - Timestamps en TIMESTAMPTZ (UTC)
--   - Catalogos pequenos y estables (tipos, estados) como tablas lookup,
--     no ENUM nativo, para permitir altas desde la UI sin migraciones.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS catalogo;   -- compartido entre modulos (articulos, geografia)
CREATE SCHEMA IF NOT EXISTS core;       -- usuarios/autenticacion (se detalla en otro modulo)
CREATE SCHEMA IF NOT EXISTS ingenieria;

-- ---------------------------------------------------------------------
-- STUBS de otros modulos (solo columnas minimas necesarias como FK).
-- Se reemplazan por las tablas reales cuando se migre cada modulo.
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS core.usuarios (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username    VARCHAR(30) NOT NULL UNIQUE,
    nombre      VARCHAR(100)
);
COMMENT ON TABLE core.usuarios IS 'Stub: modulo Auth/Usuarios se disena aparte. Se referencia aqui solo para auditoria (creado_por, etc).';

CREATE TABLE IF NOT EXISTS catalogo.clientes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(255) NOT NULL
);
COMMENT ON TABLE catalogo.clientes IS 'Stub: modulo Ventas/CRM se disena aparte (legacy: clientesalbion). El ETL de Ingenieria crea aqui filas placeholder preservando el codigo de cliente usado en of.cliente, para no bloquear la FK; se reconciliaran cuando se migre Ventas/CRM.';

