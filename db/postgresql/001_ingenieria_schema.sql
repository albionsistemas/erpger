CREATE TABLE catalogo.rubros (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(60) NOT NULL UNIQUE
);
-- legacy: rubros_albion. Se puebla via ETL preservando el id original
