CREATE TABLE ingenieria.tipos_orden (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE
);
-- legacy: ordenes_tipo. Se puebla via ETL preservando el id original
-- (of.of ya guarda el NOMBRE como texto libre, no un id, pero de todas
-- formas conservamos el id legacy de ordenes_tipo por consistencia).

CREATE TABLE ingenieria.estados_of (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE
);
-- legacy: of_estados. Se puebla via ETL preservando el id original,
-- porque 'of.estado' SI referencia este id numerico directamente.

CREATE TABLE ingenieria.estados_ot (
    id      SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(20) NOT NULL UNIQUE
);
-- legacy: ot_estados. Se puebla via ETL preservando el id original.
-- OJO: 'o_trabajo.estado' guarda el VALOR TEXTO ('C','P','80%'...)
-- directo, no el id numerico -> el ETL resuelve por texto, no por id.

CREATE TABLE ingenieria.sectores_produccion (
    id      SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE,
    orden   SMALLINT NOT NULL DEFAULT 0  -- orden tipico del flujo productivo
);
-- Reemplaza las columnas fijas CORTE/PLEG/FABRIC/MECA/PINT/ARMA de o_trabajo
-- y unifica el criterio usado para separar 'tareas' de 'tareas_mec' (legacy).
INSERT INTO ingenieria.sectores_produccion (nombre, orden) VALUES
    ('INGENIERIA', 0), ('CORTE', 1), ('PLEGADO', 2), ('FABRICACION', 3),
    ('MECANIZADO', 4), ('PINTURA', 5), ('ARMADO', 6), ('ESPERA', 7),
    ('PRODUCCION', 8), ('AJUSTE', 9), ('ALMACEN', 10), ('VARIOS', 11);
-- 'ESPERA' viene de las columnas F_ESP/U_ESP/ESP de o_trabajo, cuyos tipos
-- estan invertidos en el legacy (F_ESP varchar con la fecha real, U_ESP
-- tipado date pero vacio, ESP con el flag 'C'). Se migra respetando el
-- dato real observado, no el nombre/tipo de columna original.
-- 'PRODUCCION'/'AJUSTE'/'ALMACEN'/'VARIOS' no son etapas de una OT: son
-- areas de planta usadas solo en operarios.sector (a que sector pertenece
-- la persona). Se reutiliza la misma tabla por simplicidad ya que hay
-- solapamiento real (CORTE, PINTURA, ARMADO, MECANIZADO aplican a ambos
-- casos); si el negocio prefiere separarlas, se puede partir en dos
-- catalogos (sectores_produccion vs areas_planta) sin gran esfuerzo.

