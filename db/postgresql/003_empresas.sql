-- =====================================================================
-- Seam minimo de multi-tenancy (solo en Auth, no en tablas de negocio)
--
-- Contexto: no hay un segundo tenant real hoy -- esto es preparar el
-- terreno por si el ERP se vende a terceros mas adelante, sin construir
-- el aislamiento completo de datos (que requeriria empresa_id en cada
-- tabla de ingenieria/catalogo y filtrado por tenant en cada query del
-- backend). Eso queda para cuando exista un segundo tenant real: es
-- mecanico agregarlo entonces (columna + WHERE), no urgente ahora.
--
-- Lo unico que se agrega aca es el concepto de "empresa" en la capa de
-- Auth, porque ESO si es caro de agregar despues (cambia la forma del
-- JWT y de cada permission check).
-- =====================================================================

CREATE TABLE IF NOT EXISTS core.empresas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(150) NOT NULL,
    activa  BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE core.usuarios
    ADD COLUMN IF NOT EXISTS empresa_id BIGINT REFERENCES core.empresas(id);

CREATE INDEX IF NOT EXISTS idx_usuarios_empresa ON core.usuarios(empresa_id);

